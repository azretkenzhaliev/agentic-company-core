#!/usr/bin/env python3
"""Each role's reading index, generated from KB pages' front matter.

Per role, the pages it reads across owners: its row of "What to read" in knowledge/engineering/README.md (engineering
roles), and the pages it opened most, from an inventory (--opened: a page with "#### <role>" headings, each over a
table of "| opens | `knowledge/page.md` |" rows, made from the agents' transcripts; optional). One line per page: its path and front-matter title, and its owner when that's another role; a page in draft says so. A folder
with GROUP_AT pages or more is listed once, its pages under it. Never knowledge/research/ (raw web text), never
knowledge/_templates/ (placeholder titles), never a cold page (status archived or superseded, or named as an archive)
and never a file outside knowledge/: live state such as
ceo-questions.md has no front matter, and its path is in the agent's own file. `related` is not followed: one hop adds
about three times the pages a role opens.

With no flags it changes nothing: it prints each role's index size in characters and estimated tokens (2.65 bytes a
token, a rough fit). --write writes .claude/agent-index/<role>.md (or --out), each headed as generated, and removes
a generated index whose role now has no page. Run it again after the pages or the inventory change; never edit its
output.
"""

import argparse
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from kb_lint import is_cold, parse_front_matter  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
OUT = Path(".claude") / "agent-index"
WHAT_TO_READ = Path("knowledge") / "engineering" / "README.md"
BYTES_PER_TOKEN = 2.65
GROUP_AT = 3
HEADER = "<!-- Generated by scripts/agent_index.py"
SKIPPED = ("knowledge/research/", "knowledge/_templates/")
ROWS = {"Senior": "senior-engineer", "Code reviewer": "code-reviewer", "Design reviewer": "design-reviewer",
        "Staff": "staff-engineer", "CTO": "cto"}  # the table's first column, to agent names
PHRASES = {  # the table's words for a page, to that page under knowledge/engineering/
    "the digest": "standards/lessons-learned.md",
    "this page": "README.md",
    "the runbook": "runbooks/README.md",
    "architecture": "architecture/overview.md",
    "design": "designs/README.md",
    "roadmap": "roadmaps/README.md",
}
EVERY_STANDARD = "every standard above"
TICKED = re.compile(r"`([^`\s]+)`")
OPENED_ROLE = re.compile(r"^#### ([a-z-]+)(?: \(main session\))?\s*$")
OPENED_ROW = re.compile(r"^\| *\d+ *\| *`(knowledge/[^`]+\.md)` *\|")


def kb_path(root: Path, token: str):
    """A ticked word in the table, as a page path relative to root, or None."""
    eng = Path("knowledge") / "engineering"
    for rel in (eng / "standards" / f"{token}.md", eng / token, Path("knowledge") / token):
        if (root / rel).is_file():
            return rel.as_posix()
    return None


def table_reads(root: Path) -> dict:
    """{agent: [page paths]} from the "What to read" table's rows, both columns."""
    reads, standards = {}, []
    lines = (root / WHAT_TO_READ).read_text(encoding="utf-8").splitlines()
    for line in lines:
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if len(cells) < 3 or cells[0] not in ROWS:
            continue
        text = " ".join(cells[1:])
        pages = [p for p in (kb_path(root, t) for t in TICKED.findall(text)) if p]
        standards += [p for p in pages if "/standards/" in p and p not in standards]
        lower = text.lower()
        pages += [f"knowledge/engineering/{page}" for phrase, page in PHRASES.items() if phrase in lower]
        if EVERY_STANDARD in lower:
            pages += standards
        reads[ROWS[cells[0]]] = pages
    return reads


def opened_reads(inventory: Path) -> dict:
    """{agent: [page paths]} from the inventory's "#### <role>" tables, in their order."""
    reads, role = {}, None
    for line in inventory.read_text(encoding="utf-8").splitlines():
        if line.startswith("#"):
            match = OPENED_ROLE.match(line)
            role = match.group(1) if match else None
            continue
        row = OPENED_ROW.match(line)
        if role and row:
            reads.setdefault(role, []).append(row.group(1))
    return reads


def entry(root: Path, rel: str):
    """(path, title, owner, status) of a page an index may list, or None."""
    page = root / rel
    if not rel.startswith("knowledge/") or rel.startswith(SKIPPED) or not page.is_file():
        return None
    parsed = parse_front_matter(page.read_text(encoding="utf-8", errors="replace").splitlines())
    fields = parsed[0] if parsed else {}
    if is_cold(page) or fields.get("status") in ("archived", "superseded"):
        return None
    return rel, str(fields.get("title") or page.stem), str(fields.get("owner") or "?"), str(fields.get("status") or "")


def line_for(name: str, title: str, owner: str, status: str, role: str) -> str:
    notes = [owner] if owner != role else []
    notes += ["draft"] if status == "draft" else []
    return f"- {name}: {title}" + (f" ({', '.join(notes)})" if notes else "")


def render(role: str, entries: list, sources: str) -> str:
    folders = {}
    for rel, *rest in entries:
        folders.setdefault(rel.rsplit("/", 1)[0], []).append((rel, *rest))
    out = [f"{HEADER} from KB front matter; don't edit, run it again. -->",
           f"# What the {role} reads", "",
           f"From {sources}. One line a page: its path, its title, and its owner when that's another role. Anything "
           "else: `grep -rn '<phrase>' knowledge/`, then read the section. Not listed: knowledge/research/ (raw web "
           "text), archives, and live state under workspaces/.", ""]
    for folder in sorted(folders):
        pages = sorted(folders[folder])
        if len(pages) >= GROUP_AT:
            out.append(f"{folder}/")
            out += ["  " + line_for(rel.rsplit("/", 1)[1], *rest, role) for rel, *rest in pages]
        else:
            out += [line_for(rel, *rest, role) for rel, *rest in pages]
    return "\n".join(out) + "\n"


def shown(inventory: Path) -> str:
    """The inventory's path from its workspaces/ folder on (gitignored, in the main checkout), else its name."""
    parts = inventory.parts
    return "/".join(parts[parts.index("workspaces"):]) if "workspaces" in parts else inventory.name


def build(root: Path, roles: list, inventory) -> dict:
    """{role: index text} for every role with at least one page."""
    table = table_reads(root)
    opened = opened_reads(inventory) if inventory else {}
    indexes = {}
    for role in roles:
        sources = []
        if role in table:
            sources.append('its row of "What to read" in knowledge/engineering/README.md')
        if role in opened:
            sources.append(f"the pages it opened most, per {shown(inventory)}")
        seen, entries = set(), []
        for rel in table.get(role, []) + opened.get(role, []):
            item = None if rel in seen else entry(root, rel)
            seen.add(rel)
            if item:
                entries.append(item)
        if entries:
            indexes[role] = render(role, entries, " and ".join(sources))
    return indexes


def agent_names(root: Path) -> list:
    names = []
    for path in sorted((root / ".claude" / "agents").rglob("*.md")):
        parsed = parse_front_matter(path.read_text(encoding="utf-8").splitlines())
        names.append(str((parsed[0] if parsed else {}).get("name") or path.stem))
    return names


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--opened", type=Path, help="an inventory with the top pages opened per role")
    parser.add_argument("--write", action="store_true", help="write the indexes (default: print sizes only)")
    parser.add_argument("--out", type=Path, help="folder for the indexes (default .claude/agent-index/)")
    parser.add_argument("--root", type=Path, default=ROOT, help=argparse.SUPPRESS)
    args = parser.parse_args(argv)
    if args.opened and not args.opened.is_file():
        print(f"no such inventory: {args.opened}", file=sys.stderr)
        return 2
    indexes = build(args.root, agent_names(args.root), args.opened)
    out = args.out or args.root / OUT
    print(f"{'role':20} {'pages':>5} {'chars':>6} {'~tokens':>7}")
    for role, text in sorted(indexes.items(), key=lambda kv: -len(kv[1])):
        pages = sum(1 for line in text.splitlines() if line.lstrip().startswith("- "))
        print(f"{role:20} {pages:5} {len(text):6} {round(len(text.encode('utf-8')) / BYTES_PER_TOKEN):7}")
        if args.write:
            out.mkdir(parents=True, exist_ok=True)
            (out / f"{role}.md").write_text(text, encoding="utf-8")
    for old in sorted(out.glob("*.md")) if args.write and out.is_dir() else []:
        if old.stem not in indexes and old.read_text(encoding="utf-8").startswith(HEADER):
            old.unlink()
            print(f"removed {old.name}: its role has no page now")
    return 0


if __name__ == "__main__":
    sys.exit(main())
